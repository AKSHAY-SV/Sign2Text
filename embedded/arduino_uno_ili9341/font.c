uint8_t font5x7_column(char c, uint8_t column) {
    static const uint8_t question[5] = {0x02,0x01,0x51,0x09,0x06};
    if (column >= 5) return 0;
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    if (c >= 'A' && c <= 'Z') return letters[(uint8_t)(c - 'A')][column];
    if (c >= '0' && c <= '9') return digits[(uint8_t)(c - '0')][column];
    switch (c) {
    case ' ': return 0;
    case '.': { static const uint8_t v[5]={0,0x60,0x60,0,0}; return v[column]; }
    case ',': { static const uint8_t v[5]={0,0x80,0x60,0,0}; return v[column]; }
    case '!': { static const uint8_t v[5]={0,0,0x5F,0,0}; return v[column]; }
    case '?': return question[column];
    case '-': { static const uint8_t v[5]={0x08,0x08,0x08,0x08,0x08}; return v[column]; }
    case ':': { static const uint8_t v[5]={0,0x36,0x36,0,0}; return v[column]; }
    case '/': { static const uint8_t v[5]={0x20,0x10,0x08,0x04,0x02}; return v[column]; }
    default: return question[column];
    }
}
